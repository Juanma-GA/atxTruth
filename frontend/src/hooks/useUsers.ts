import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { useTranslation } from 'react-i18next';
import { toast } from 'sonner';

import { api } from '@/services/api';
import { errorMessage } from '@/services/apiErrors';
import { queryKeys } from '@/services/queryKeys';
import type { Role, User, UserWithTemporaryPassword } from '@/types/api';

export function useUsers(includeDeleted: boolean) {
  return useQuery({
    queryKey: queryKeys.users(includeDeleted),
    queryFn: () => api.get<User[]>(`/api/users?include_deleted=${includeDeleted}`),
  });
}

type Patch = (user: User) => User | null;

/**
 * Optimistic user mutation (HR20): `optimistic` edits (or removes, returning null) the cached row
 * at once; the server answer replaces it; a rejection restores every cached list and explains why.
 */
function useOptimisticUserMutation<V extends { id: string }>(
  call: (vars: V) => Promise<User | undefined>,
  optimistic: (vars: V) => Patch,
  successKey: string,
) {
  const queryClient = useQueryClient();
  const { t } = useTranslation();
  return useMutation({
    mutationFn: call,
    onMutate: async (vars) => {
      await queryClient.cancelQueries({ queryKey: queryKeys.usersAll });
      const snapshot = queryClient.getQueriesData<User[]>({ queryKey: queryKeys.usersAll });
      const patch = optimistic(vars);
      queryClient.setQueriesData<User[]>({ queryKey: queryKeys.usersAll }, (list) =>
        list?.flatMap((u) => {
          if (u.id !== vars.id) return [u];
          const next = patch(u);
          return next ? [next] : [];
        }),
      );
      return { snapshot };
    },
    onError: (error, _vars, context) => {
      context?.snapshot.forEach(([key, data]) => queryClient.setQueryData(key, data));
      toast.error(errorMessage(t, error));
    },
    onSuccess: () => toast.success(t(successKey)),
    onSettled: () => queryClient.invalidateQueries({ queryKey: queryKeys.usersAll }),
  });
}

export function useChangeRole() {
  return useOptimisticUserMutation<{ id: string; role: Role }>(
    ({ id, role }) => api.patch<User>(`/api/users/${id}`, { role }),
    ({ role }) => (u) => ({ ...u, role }),
    'users.roleChanged',
  );
}

export function useDeactivateUser(showDeleted: boolean) {
  return useOptimisticUserMutation<{ id: string }>(
    ({ id }) => api.post<User>(`/api/users/${id}/deactivate`),
    () => (u) => (showDeleted ? { ...u, deleted_at: new Date().toISOString() } : null),
    'users.deactivatedToast',
  );
}

export function useRestoreUser() {
  return useOptimisticUserMutation<{ id: string }>(
    ({ id }) => api.post<User>(`/api/users/${id}/restore`),
    () => (u) => ({ ...u, deleted_at: null }),
    'users.restoredToast',
  );
}

export function useDeleteUserPermanently() {
  return useOptimisticUserMutation<{ id: string; confirm_email: string }>(
    ({ id, confirm_email }) => api.post<undefined>(`/api/users/${id}/delete-permanently`, { confirm_email }),
    () => () => null,
    'users.deleted',
  );
}

/** Not optimistic (HR20 exception): the id and the temporary password are generated by the server. */
export function useCreateUser() {
  const queryClient = useQueryClient();
  return useMutation({
    mutationFn: (body: { email: string; display_name: string; role: Role }) =>
      api.post<UserWithTemporaryPassword>('/api/users', body),
    onSuccess: () => queryClient.invalidateQueries({ queryKey: queryKeys.usersAll }),
  });
}

/** Not optimistic for the same reason: the new temporary password comes from the server. */
export function useResetPassword() {
  return useMutation({
    mutationFn: (id: string) => api.post<UserWithTemporaryPassword>(`/api/users/${id}/reset-password`),
  });
}
